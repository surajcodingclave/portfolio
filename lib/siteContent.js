export function getSiteContent(siteInfo) {
  const content = siteInfo?.siteContent || {};
  const oldName = content.navigation?.logoText === 'Suraj';
  const merged = {
    ...defaultSiteContent,
    ...content,
    seo: { ...defaultSiteContent.seo, ...content.seo },
    appearance: { ...defaultSiteContent.appearance, ...content.appearance },
    navigation: {
      ...defaultSiteContent.navigation,
      ...content.navigation,
      ...(oldName && { logoText: 'Suraj Gupta', logoSuffix: '' }),
      ...(content.navigation?.experienceLabel === 'My Approach' && { experienceLabel: 'Experience' }),
    },
    home: { ...defaultSiteContent.home, ...content.home },
    about: { ...defaultSiteContent.about, ...content.about },
    projects: { ...defaultSiteContent.projects, ...content.projects },
    services: { ...defaultSiteContent.services, ...content.services },
    skills: { ...defaultSiteContent.skills, ...content.skills },
    experience: { ...defaultSiteContent.experience, ...content.experience },
    contact: { ...defaultSiteContent.contact, ...content.contact },
    footer: { ...defaultSiteContent.footer, ...content.footer },
    marqueeSkills: content.marqueeSkills || defaultSiteContent.marqueeSkills,
  };
  for (const section of ['home', 'about', 'projects', 'services', 'skills', 'experience', 'contact', 'footer']) {
    for (const [key, value] of Object.entries(merged[section] || {})) {
      if (typeof value === 'string' && /(?:5\s*\+?\s*years?|five years|2\s*\+?\s*years?|two years)/i.test(value)) {
        merged[section][key] = defaultSiteContent[section][key] || value.replace(/(?:5\s*\+?\s*years?|five years|2\s*\+?\s*years?|two years)/ig, '3 years');
      }
    }
  }
  if (content.experience?.eyebrow === 'A collaborative process') {
    merged.experience = { ...merged.experience, ...defaultSiteContent.experience };
  }
  return merged;
}

export const themeColors = { accent: '#3b82f6', highlight: '#22d3ee', surface: '#020617', text: '#f8fafc' };

export function themeStyle(siteInfo) {
  const appearance = siteInfo?.siteContent?.appearance || {};
  return Object.fromEntries(Object.entries(themeColors).map(([key, fallback]) => [
    '--portfolio-' + key,
    /^#[0-9a-f]{6}$/i.test(appearance[key] || '') ? appearance[key] : fallback,
  ]));
}
